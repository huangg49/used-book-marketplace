export function withCatalogVocabularyV2(spec: CollectionSpec): CollectionSpec {
  if (spec.name !== 'catalog_revisions') return spec;
  return {
    ...spec,
    schema: {
      ...spec.schema,
      properties: {
        ...spec.schema.properties,
        categoryId: {
          bsonType: ['string', 'null'],
          enum: [...catalogVocabularyV2.categoryIds, null],
        },
        attributes: {
          bsonType: 'object',
          additionalProperties: false,
          maxProperties: 16,
          properties: Object.fromEntries(
            Object.entries(catalogVocabularyV2.attributes).map(
              ([key, values]) => [
                key,
                {
                  bsonType: 'array',
                  minItems: 1,
                  maxItems: 16,
                  uniqueItems: true,
                  items: { bsonType: 'string', enum: values },
                },
              ],
            ),
          ),
        },
      },
    },
  };
}
