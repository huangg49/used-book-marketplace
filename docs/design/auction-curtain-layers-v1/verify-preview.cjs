// Scoped review of the standalone design preview; no application/API/DB writes.
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.CURTAIN_PLAYWRIGHT_PATH || 'playwright');
const assert = require('node:assert/strict');
const sharp = require(process.env.CURTAIN_SHARP_PATH || 'sharp');
let qaBrowser;
(async () => {
  const browser = await chromium.launch({ headless: true });
  qaBrowser = browser;
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:5191/', { waitUntil: 'networkidle' });
  await page.locator('#loadState').filter({ hasText: 'Đã tải 15 PNG' }).waitFor();
  await page.locator('#nav').uncheck();
  await page.locator('#stage').screenshot({ path: path.join(__dirname, 'evidence/open.png') });
  await page.locator('#closed').click();
  await page.locator('#stage').screenshot({ path: path.join(__dirname, 'evidence/closed.png') });
  const cream = await page.locator('#stage').screenshot();
  await page.locator('#stage').evaluate(el => el.style.background = '#1266ba');
  const blue = await page.locator('#stage').screenshot();
  await page.locator('#stage').evaluate(el => el.style.background = '');
  const a = await sharp(cream).removeAlpha().raw().toBuffer();
  const b = await sharp(blue).removeAlpha().raw().toBuffer();
  let changed = 0;
  for (let i=0;i<a.length;i+=3) if(a[i]!==b[i]||a[i+1]!==b[i+1]||a[i+2]!==b[i+2]) changed++;
  assert.equal(changed, 0, 'closed curtain must completely hide background');
  assert.equal(await page.locator('[data-layer="inner-closed-left"]').isVisible(), true);
  assert.equal(await page.locator('[data-layer="inner-open-left"]').isVisible(), false);
  await page.locator('#toggle-valance-front').uncheck();
  assert.equal(await page.locator('[data-layer="valance-front"]').isVisible(), false);
  await page.locator('#restore').click();
  await page.locator('#open').click();
  await page.locator('#nav').check();
  await page.locator('#slot').selectOption('45');
  assert.equal(await page.locator('#navbar').evaluate(el => getComputedStyle(el).zIndex), '45');
  await page.screenshot({ path: path.join(__dirname, 'evidence/layer-controls.png'), fullPage: true });
  await page.locator('#slot').selectOption('90');
  await page.locator('#stage').screenshot({ path: path.join(__dirname, 'evidence/navbar-front.png') });
  await page.locator('#slot').selectOption('10');
  await page.locator('#closed').click();
  await page.locator('#stage').screenshot({ path: path.join(__dirname, 'evidence/navbar-behind-closed.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#open').click();
  await page.locator('#slot').selectOption('45');
  await page.screenshot({ path: path.join(__dirname, 'evidence/mobile.png'), fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false, 'preview must fit mobile width');
  assert.deepEqual(errors, []);
  const result = { scope: 'standalone art-layer preview only', browser: 'Chromium', viewports: ['1440×1050', '390×844'], pngAssetsDecoded: 15, svgAssetsDecoded: 1, layerInstances: 20, poseSwitch: 'PASS', closedBackgroundChangedPixels: changed, individualVisibility: 'PASS', navbarSlot: 'PASS', mobileOverflow: 'none', pageErrors: errors, animation: 'NOT RUN / not implemented', applicationIntegration: 'NOT RUN / unchanged' };
  await fs.writeFile(path.join(__dirname, 'evidence/checks.json'), JSON.stringify(result, null, 2) + '\n');
  console.log(JSON.stringify(result));
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if(qaBrowser) await qaBrowser.close(); });
